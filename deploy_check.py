"""Deployment check: size and accuracy of the exported global model in float32 and int8.

Evaluates the model that export_model.py wrote to deploy/model/ (the proposed scheme in the main
configuration, alpha = 0.5, seed 0), so the paper, the phone page and the PC API all describe the
same weights. int8: per-tensor symmetric quantisation of weight tensors, biases kept in float32,
as in dynamic-range quantisation. Writes results/deploy_check.json.
"""
import json
import os

import torch

from hfl import data as D
from hfl.model import build_model

ROOT = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(ROOT, "deploy", "model")


def evaluate(model, x, y, bs=2000):
    with torch.no_grad():
        return sum((model(x[i:i + bs]).argmax(1) == y[i:i + bs]).sum().item() for i in range(0, len(x), bs)) / len(x)


def main():
    with open(os.path.join(MODEL_DIR, "model.json"), encoding="utf-8") as f:
        meta = json.load(f)
    model = build_model("fmnist").eval()
    model.load_state_dict(torch.load(os.path.join(MODEL_DIR, "model_fp32.pt"), map_location="cpu"))
    _, _, x_te, y_te = D.load("fmnist", os.path.join(ROOT, "data"), torch.device("cpu"))
    acc_fp32 = evaluate(model, x_te, y_te)

    int8_bytes = 0
    with torch.no_grad():
        for _, p in model.named_parameters():
            if p.dim() > 1:  # weight tensors: int8 values + one float32 scale
                scale = p.abs().max() / 127.0
                p.copy_(torch.clamp(torch.round(p / scale), -127, 127) * scale)
                int8_bytes += p.numel() + 4
            else:            # biases stay float32
                int8_bytes += p.numel() * 4
    acc_int8 = evaluate(model, x_te, y_te)

    n_params = sum(p.numel() for p in model.parameters())
    out = dict(model_version=meta["version"], config=meta["source_run"], params=n_params, fp32_bytes=n_params * 4,
               int8_bytes=int8_bytes, compression=n_params * 4 / int8_bytes, acc_fp32=acc_fp32, acc_int8=acc_int8,
               acc_change_points=100 * (acc_int8 - acc_fp32))
    with open(os.path.join(ROOT, "results", "deploy_check.json"), "w") as f:
        json.dump(out, f, indent=1)
    print(json.dumps(out, indent=1))
    per_class(meta, x_te, y_te)


def per_class(meta, x_te, y_te):
    """Per-class precision, recall and F1 and the confusion matrix of the exported float32 model."""
    import numpy as np
    import analyze  # shared figure style and output folders
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap

    model = build_model("fmnist").eval()
    model.load_state_dict(torch.load(os.path.join(MODEL_DIR, "model_fp32.pt"), map_location="cpu"))
    with torch.no_grad():
        pred = torch.cat([model(x_te[i:i + 2000]).argmax(1) for i in range(0, len(x_te), 2000)]).numpy()
    true = y_te.numpy()
    cm = np.zeros((10, 10), dtype=int)
    np.add.at(cm, (true, pred), 1)
    tp = np.diag(cm).astype(float)
    prec, rec = tp / cm.sum(0), tp / cm.sum(1)
    f1 = 2 * prec * rec / (prec + rec)
    short = ["T-shirt/top", "Trouser", "Pullover", "Dress", "Coat", "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot"]
    rows = [dict(cls=c, precision=float(p), recall=float(r), f1=float(f)) for c, p, r, f in zip(short, prec, rec, f1)]
    off = cm.astype(float) / cm.sum(1, keepdims=True)
    np.fill_diagonal(off, 0)
    top = sorted(((off[i, j], short[i], short[j]) for i in range(10) for j in range(10)), reverse=True)[:5]
    res = dict(model_version=meta["version"], accuracy=float(tp.sum() / cm.sum()), macro_f1=float(f1.mean()),
               per_class=rows, confusion_matrix=cm.tolist(),
               top_confusions=[dict(true=a, predicted=b, share_of_true=float(s)) for s, a, b in top])
    with open(os.path.join(ROOT, "results", "per_class.json"), "w") as f:
        json.dump(res, f, indent=1)

    lines = [r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{l ccc}", r"\toprule",
             r"Class & Precision & Recall & F1 \\", r"\midrule"]
    for r in rows:
        lines.append(f"{r['cls']} & {100 * r['precision']:.1f} & {100 * r['recall']:.1f} & {100 * r['f1']:.1f} \\\\")
    lines += [r"\midrule", f"Macro average & {100 * prec.mean():.1f} & {100 * rec.mean():.1f} & {100 * f1.mean():.1f} \\\\",
              r"\bottomrule", r"\end{tabular}"]
    with open(os.path.join(analyze.TAB, "tab_perclass.tex"), "w") as f:
        f.write("% generated by deploy_check.py -- do not edit\n" + "\n".join(lines) + "\n")

    labels = ["T-shirt", "Trouser", "Pullover", "Dress", "Coat", "Sandal", "Shirt", "Sneaker", "Bag", "Boot"]
    norm = cm / cm.sum(1, keepdims=True)
    fig, ax = plt.subplots(figsize=(analyze.COL_W, 2.9))
    cmap = LinearSegmentedColormap.from_list("seq", ["#ffffff", "#2a78d6", "#0b3a75"])
    im = ax.imshow(norm, cmap=cmap, vmin=0, vmax=1)
    for i in range(10):
        for j in range(10):
            v = norm[i, j]
            if v >= 0.03:
                ax.text(j, i, f"{100 * v:.0f}", ha="center", va="center", fontsize=5.2,
                        color="#ffffff" if v > 0.5 else "#0b0b0b")
    ax.set_xticks(range(10), labels, rotation=45, ha="right", fontsize=6)
    ax.set_yticks(range(10), labels, fontsize=6)
    ax.set_xlabel("predicted class")
    ax.set_ylabel("true class")
    ax.grid(False)
    for s in ax.spines.values():
        s.set_visible(False)
    cb = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.03)
    cb.set_label("share of the true class (%)", fontsize=6.5)
    cb.set_ticks([0, 0.25, 0.5, 0.75, 1], labels=["0", "25", "50", "75", "100"])
    cb.ax.tick_params(labelsize=6)
    cb.outline.set_visible(False)
    analyze.save(fig, "fig_confusion")
    print(json.dumps({k: res[k] for k in ("accuracy", "macro_f1", "top_confusions")}, indent=1))


if __name__ == "__main__":
    main()
